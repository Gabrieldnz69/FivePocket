#!/usr/bin/env python3
"""check_apk_sources.py --apk APK=TREE_IN_TARBALL [...] --source SOURCE.tar.xz|DIR [--package dev/recompbootstrap/smoke]

The GPL corresponding-source check for the Android downloads (D1, 2026-11-06): every class of PACKAGE in each APK's
classes*.dex (outer class: '$' parts dropped) must have its .java under the named tree of the source download
(TREE/app/src/<set>/java/PACKAGE/<Class>.java for any source set, or a top-level class of that name declared in a .java of
that package). Reads the dex type table with the standard library only. Exit 0: every class found; 1: classes without
source (listed); 2: refused (unreadable input)."""
import argparse, io, re, struct, sys, tarfile, zipfile
from pathlib import Path

def uleb(b, i):
    r = s = 0
    while True:
        x = b[i]; i += 1; r |= (x & 0x7f) << s; s += 7
        if x < 0x80: return r, i

def dex_types(data):
    if data[:4] != b'dex\n': raise ValueError('not a dex file')
    sid_size, sid_off, tid_size, tid_off = struct.unpack_from('<IIII', data, 0x38)
    def string(i):
        off = struct.unpack_from('<I', data, sid_off + 4 * i)[0]
        _, j = uleb(data, off); k = data.index(b'\0', j); return data[j:k].decode('utf-8', 'replace')
    return [string(struct.unpack_from('<I', data, tid_off + 4 * t)[0]) for t in range(tid_size)]

def defined_classes(data):
    """class_defs only (types the dex defines, not ones it references)"""
    types = dex_types(data)
    cd_size, cd_off = struct.unpack_from('<II', data, 0x60)
    return [types[struct.unpack_from('<I', data, cd_off + 32 * i)[0]] for i in range(cd_size)]

def apk_classes(apk, package):
    out = set()
    with zipfile.ZipFile(apk) as z:
        for n in z.namelist():
            if re.fullmatch(r'classes\d*\.dex', n):
                for d in defined_classes(z.read(n)):
                    if d.startswith('L' + package + '/') and d.endswith(';'):
                        rest = d[len(package) + 2:-1]
                        if '/' not in rest: out.add(rest.split('$')[0].split('-')[0])   # D8 synthetics 'Name-IA' belong to Name
    return out

def source_files(src):
    """(the .java texts by path, every file name) of one source download: a folder or a tarball"""
    files, all_names = {}, set()
    if Path(src).is_dir():
        for p in Path(src).rglob('*'):
            if p.is_file(): all_names.add(p.relative_to(src).as_posix())
            if p.suffix == '.java': files[p.relative_to(src).as_posix()] = p.read_text('utf-8', 'replace')
        return files, all_names
    else:
        with tarfile.open(src) as t:
            for m in t.getmembers():
                if m.isfile(): all_names.add(m.name)
                if m.isfile() and m.name.endswith('.java'):
                    files[m.name] = t.extractfile(m).read().decode('utf-8', 'replace')
    return files, all_names

def main(argv=None):
    ap = argparse.ArgumentParser(); ap.add_argument('--apk', action='append', required=True, metavar='APK=TREE')
    ap.add_argument('--source', required=True); ap.add_argument('--package', default='dev/recompbootstrap/smoke')
    a = ap.parse_args(argv)
    try:
        files, all_names = source_files(a.source)
    except (OSError, tarfile.TarError) as e:
        print('SOURCE_CHECK_REFUSED', e, file=sys.stderr); return 2
    bad = 0
    for spec in a.apk:
        apk, _, tree = spec.partition('=')
        try:
            classes = apk_classes(apk, a.package)
        except (OSError, ValueError, zipfile.BadZipFile) as e:
            print('SOURCE_CHECK_REFUSED', apk, e, file=sys.stderr); return 2
        tree = tree.strip('/')
        pkg_files = {n: s for n, s in files.items() if n.startswith(tree + '/') and f'/java/{a.package}/' in n}
        names = {Path(n).stem for n in pkg_files}
        declared = set()
        for s in pkg_files.values():
            declared |= set(re.findall(r'^(?:public\s+|final\s+|abstract\s+)*(?:class|interface|enum|record)\s+(\w+)', s, re.M))
        # R / BuildConfig are generated by the build from the tree's res/ and build file: they need those, not a .java
        has_res = any(n.startswith(tree + '/') and '/src/main/res/' in n for n in all_names)
        generated = {'R', 'BuildConfig'} if has_res else {'BuildConfig'}
        missing = sorted(c for c in classes if c not in names and c not in declared and c not in generated)
        print(f'SOURCE_CHECK {Path(apk).name} tree={tree}: {len(classes)} classes, {len(missing)} without source' + (': ' + ' '.join(missing) if missing else ''))
        bad += len(missing)
    print('SOURCE_CHECK', 'PASS' if not bad else f'FAIL {bad}')
    return 0 if not bad else 1

if __name__ == '__main__':
    sys.exit(main())
